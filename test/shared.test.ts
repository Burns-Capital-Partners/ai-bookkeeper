test("Drive handoff copies complete immutable records and distinguishes local backup from cloud receipt", t => {
  const base = mkdtempSync(join(tmpdir(), "bookkeeper-shared-")), local = join(base, "local"), drive = join(base, "Drive");
  mkdirSync(local); mkdirSync(drive); mkdirSync(join(drive, "inbox"));
  const state = new BookkeeperState(join(local, "state.db")); t.after(() => state.close());
  const options = { path: drive, localStateDirectory: local, backupKey: randomBytes(32).toString("hex") };
  const payload = { version: 1, id: "input" };
  writeFileSync(join(drive, "inbox", "message.json"), JSON.stringify(payload));
  writeFileSync(join(drive, "inbox", "partial.json"), '{"unfinished":');
  importSharedInbox(options, join(local, "handoff"));
  assert.deepEqual(JSON.parse(readFileSync(join(local, "handoff", "inbox", "drive-message.json"), "utf8")), payload);
  assert.equal(existsSync(join(local, "handoff", "inbox", "drive-partial.json")), false);
  importSharedInbox(options, join(local, "handoff"));
  publishShared(config, state, options);
  assert.ok(JSON.parse(readFileSync(join(drive, "current.json"), "utf8")).context);
  const saved = sharedState(state); assert.ok(saved.backup); assert.equal(saved.backup.cloudReceipt, undefined);
  assert.throws(() => acceptSharedReceipt({ target: "backup", hash: "wrong", file: saved.backup!.file, receipt: "drive-id" }, state), /does not match/);
  acceptSharedReceipt({ target: "backup", hash: saved.backup.hash, file: saved.backup.file, receipt: "verified-drive-id" }, state);
  assert.equal(sharedState(state).backup?.cloudReceipt, "verified-drive-id");
  publishShared(config, state, options); assert.equal(sharedState(state).backup?.file, saved.backup.file);
  writeFileSync(join(drive, "inbox", "message.json"), JSON.stringify({ ...payload, changed: true }));
  writeFileSync(join(drive, "inbox", "unrelated.json"), JSON.stringify({ ...payload, id: "independent" }));
  assert.throws(() => importSharedInbox(options, join(local, "handoff")), /immutable/);
  assert.equal(existsSync(join(local, "handoff", "inbox", "drive-unrelated.json")), true);
  assert.throws(() => sharedRoot({ ...options, localStateDirectory: drive }), /outside/);
});

test("same-day completed and failed runs each retain a fresh recoverable backup", t => {
  const base = mkdtempSync(join(tmpdir(), "bookkeeper-backup-rerun-")), local = join(base, "local"), drive = join(base, "Drive");
  mkdirSync(local); mkdirSync(drive);
  const state = new BookkeeperState(join(local, "state.db")); t.after(() => state.close());
  const options = { path: drive, localStateDirectory: local, backupKey: randomBytes(32).toString("hex") };
  publishShared(config, state, options, {}, new Date("2026-10-06T10:00:00Z"));
  const preparedBackup = sharedState(state).backup!.file;
  state.markProcessed("first-source", config.company.name, "rental-income", "first-journal");
  const firstRun = { status: "complete", finishedAt: "2026-10-06T10:05:00Z" };
  state.setRuntime("last-run", firstRun);
  publishShared(config, state, options, { lastRun: firstRun }, new Date(firstRun.finishedAt));
  const firstBackup = sharedState(state).backup!.file;
  assert.notEqual(firstBackup, preparedBackup);
  state.markProcessed("second-source", config.company.name, "rental-income", "second-journal");
  const secondRun = { status: "error", finishedAt: "2026-10-06T11:00:00Z", error: "Failure after independently completed work" };
  state.setRuntime("last-run", secondRun);
  publishShared(config, state, options, { lastRun: secondRun }, new Date(secondRun.finishedAt));
  const saved = sharedState(state).backup!;
  assert.notEqual(saved.file, firstBackup);
  assert.ok(existsSync(join(drive, "backups", preparedBackup)));
  assert.ok(existsSync(join(drive, "backups", firstBackup)));
  const restoredPath = join(local, "restored.db");
  restoreBackup(join(drive, "backups", saved.file), restoredPath, config.company.zohoOrgId, options.backupKey, drive);
  const restored = new BookkeeperState(restoredPath); t.after(() => restored.close());
  assert.equal(restored.isProcessed("first-source"), true);
  assert.equal(restored.isProcessed("second-source"), true);
  assert.deepEqual(restored.getRuntime("last-run"), secondRun);
  publishShared(config, state, options, { lastRun: secondRun }, new Date("2026-10-06T11:05:00Z"));
  assert.equal(sharedState(state).backup!.file, saved.file);
});
test("an unavailable Drive folder does not prevent ordinary daily bookkeeping", async t => {
  const local = mkdtempSync(join(tmpdir(), "bookkeeper-drive-offline-"));
  const state = new BookkeeperState(join(local, "state.db")); t.after(() => state.close());
  const zoho = { listBankTransactions: async () => [], getProfitAndLoss: async () => ({}) } as unknown as ZohoBooksClient;
  const run = await runDaily(config, zoho, state, join(local, "handoff"), { shared: { path: join(local, "absent"), localStateDirectory: local } });
  assert.ok(run.categorization); assert.equal(run.status, "complete");
  assert.equal(existsSync(join(local, "absent")), false);
  assert.ok(state.getOpenFlags(config.company.name).some(f => f.key === "shared:publish"));
});
test("a failed encrypted backup still publishes fresh context and explicitly reports missing recovery", t => {
  const base = mkdtempSync(join(tmpdir(), "bookkeeper-backup-failure-")), drive = join(base, "Drive"), local = join(base, "local");
  mkdirSync(drive); mkdirSync(local); const state = new BookkeeperState(join(local, "state.db")); t.after(() => state.close());
  publishShared(config, state, { path: drive, localStateDirectory: local, backupKey: "invalid" });
  const snapshot = JSON.parse(readFileSync(join(drive, "current.json"), "utf8"));
  assert.ok(snapshot.context); assert.match(snapshot.storage.error, /backup failed/); assert.equal(snapshot.storage.backup, undefined);
});
